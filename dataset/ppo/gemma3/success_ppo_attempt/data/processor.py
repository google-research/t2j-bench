"""Unsupervised dataset processor for Gemma3 PPO (prompt-only)."""

import logging
from dataclasses import dataclass
from typing import Any, Optional

from .constants import IGNORE_INDEX

logger = logging.getLogger(__name__)


def infer_seqlen(source_len: int, target_len: int, cutoff_len: int) -> tuple[int, int]:
    """Compute the real sequence length after truncation by the cutoff_len."""
    if source_len + target_len <= cutoff_len:
        return source_len, target_len

    if source_len > cutoff_len:
        return cutoff_len, 0

    return source_len, cutoff_len - source_len


@dataclass
class UnsupervisedDatasetProcessor:
    """Processor for unsupervised (prompt-only) data for PPO.

    For PPO training, we only need the prompt tokens. The response
    will be generated by the model during the rollout phase.
    """
    template: Any
    tokenizer: Any
    processor: Any = None
    data_args: Any = None

    def _encode_data_example(self, example: dict[str, Any]) -> dict[str, Any]:
        """Encode a single data example into prompt-only input_ids."""
        prompt = example.get("_prompt", [])
        response = example.get("_response", [])
        system = example.get("_system", "")
        tools = example.get("_tools", "")
        images = example.get("_images", None)

        cutoff_len = getattr(self.data_args, "cutoff_len", 2048)

        # For PPO: if response exists, include it; otherwise add empty assistant msg
        if response:
            messages = prompt + response
        else:
            messages = prompt + [{"role": "assistant", "content": ""}]

        # Process messages through mm_plugin
        if hasattr(self.template, "mm_plugin"):
            messages = self.template.mm_plugin.process_messages(
                messages, images=images, processor=self.processor,
            )

        input_ids, labels = self.template.encode_oneturn(
            self.tokenizer, messages, system=system, tools=tools,
        )

        # Process token IDs through mm_plugin
        if hasattr(self.template, "mm_plugin"):
            input_ids, labels = self.template.mm_plugin.process_token_ids(
                input_ids, labels=labels, images=images,
                tokenizer=self.tokenizer, processor=self.processor,
            )

        source_len, target_len = infer_seqlen(
            len(input_ids), len(labels), cutoff_len
        )
        input_ids = input_ids[:source_len]
        labels = labels[:target_len]

        result = {
            "input_ids": input_ids,
            "attention_mask": [1] * len(input_ids),
            "labels": labels,
        }

        # Pass through images for collator
        if images:
            result["_images"] = images

        return result

    def preprocess_dataset(self, examples: dict[str, list[Any]]) -> dict[str, list[Any]]:
        """Build model inputs: prompt-only input_ids + attention_mask."""
        results = {
            "input_ids": [],
            "attention_mask": [],
            "labels": [],
            "_images": [],
        }

        batch_size = len(next(iter(examples.values())))
        for i in range(batch_size):
            example = {k: v[i] for k, v in examples.items()}
            prompt = example.get("_prompt", [])

            if not prompt:
                continue

            encoded = self._encode_data_example(example)
            if encoded and len(encoded["input_ids"]) > 0:
                for key in results:
                    if key in encoded:
                        results[key].append(encoded[key])
                    else:
                        results[key].append(None)

        return results

    def print_data_example(self, example: dict[str, list[int]]) -> None:
        input_ids = example.get("input_ids", [])
        labels = example.get("labels", [])

        logger.info(f"input_ids length: {len(input_ids)}")
        logger.info(f"labels length: {len(labels)}")
        logger.info(f"inputs:\n{self.tokenizer.decode(input_ids)}")
        if labels:
            logger.info(f"labels:\n{self.tokenizer.decode(labels)}")
